import { NextRequest, NextResponse } from "next/server";
import { getServerSession } from "next-auth";
import connectDB from "@/lib/mongodb";
import MarketingPost from "../../../../models/MarketingPost";
import { OpenAI } from "openai";

// Initialize OpenAI client for fallback
const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY,
});

// Perplexity API configuration
const PERPLEXITY_API_KEY = process.env.PERPLEXITY_API_KEY;
const PERPLEXITY_BASE_URL = "https://api.perplexity.ai";
const PERPLEXITY_MODEL = "sonar-pro";

export async function POST(request: NextRequest) {
  try {
    // Check authentication (optional for testing)
    const session = await getServerSession();
    const userId = session?.user?.email || "demo-user@example.com";

    const { websiteUrl, contentType, tone, analysis } = await request.json();

    if (!websiteUrl) {
      return NextResponse.json(
        { error: "Website URL is required" },
        { status: 400 }
      );
    }

    // Connect to database
    await connectDB();

    // Generate content using analysis results (Perplexity API with OpenAI fallback)
    const content = await generateMarketingContent(
      websiteUrl,
      contentType,
      tone,
      analysis
    );

    // Save to database
    const marketingPost = new MarketingPost({
      userId: userId,
      content,
      websiteUrl,
      contentType,
      tone,
      status: "draft",
    });

    await marketingPost.save();

    return NextResponse.json({
      content,
      postId: marketingPost._id,
    });
  } catch (error) {
    console.error("Error generating content:", error);
    return NextResponse.json(
      { error: "Failed to generate content" },
      { status: 500 }
    );
  }
}

async function generateMarketingContent(
  websiteUrl: string,
  contentType: string,
  tone: string,
  analysis?: any
): Promise<string> {
  // Try Perplexity API first
  if (PERPLEXITY_API_KEY) {
    try {
      return await generateWithPerplexity(
        websiteUrl,
        contentType,
        tone,
        analysis
      );
    } catch (perplexityError) {
      console.error("Perplexity API error:", perplexityError);
      console.log("Falling back to OpenAI...");
    }
  }

  // Fallback to OpenAI
  if (process.env.OPENAI_API_KEY) {
    try {
      return await generateWithOpenAI(websiteUrl, contentType, tone, analysis);
    } catch (openaiError) {
      console.error("OpenAI API error:", openaiError);
    }
  }

  // Final fallback
  return generateFallbackContent(websiteUrl, contentType, tone, analysis);
}

async function generateWithPerplexity(
  websiteUrl: string,
  contentType: string,
  tone: string,
  analysis?: any
): Promise<string> {
  const prompt = createPrompt(websiteUrl, contentType, tone, analysis);

  try {
    const response = await fetch(`${PERPLEXITY_BASE_URL}/chat/completions`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${PERPLEXITY_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: PERPLEXITY_MODEL,
        messages: [
          {
            role: "system",
            content:
              "You are an expert marketing copywriter who creates engaging, conversion-focused content for websites and social media platforms. Always provide high-quality, actionable content based on the provided analysis.",
          },
          {
            role: "user",
            content: prompt,
          },
        ],
        max_tokens: 500,
        temperature: 0.7,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error(`Perplexity API error ${response.status}:`, errorText);
      throw new Error(
        `Perplexity API error: ${response.status} - ${errorText}`
      );
    }

    const data = await response.json();
    const content = data.choices[0]?.message?.content;

    if (!content) {
      throw new Error("No content generated by Perplexity API");
    }

    return content;
  } catch (error) {
    console.error("Perplexity API request failed:", error);
    throw error;
  }
}

async function generateWithOpenAI(
  websiteUrl: string,
  contentType: string,
  tone: string,
  analysis?: any
): Promise<string> {
  const prompt = createPrompt(websiteUrl, contentType, tone, analysis);

  try {
    const response = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${process.env.OPENAI_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "gpt-4",
        messages: [
          {
            role: "system",
            content:
              "You are an expert marketing copywriter who creates engaging, conversion-focused content for websites and social media platforms. Use the provided analysis to create highly targeted content.",
          },
          {
            role: "user",
            content: prompt,
          },
        ],
        max_tokens: 500,
        temperature: 0.7,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error(`OpenAI API error ${response.status}:`, errorText);
      throw new Error(`OpenAI API error: ${response.status} - ${errorText}`);
    }

    const data = await response.json();
    const content = data.choices[0]?.message?.content;

    if (!content) {
      throw new Error("No content generated by OpenAI API");
    }

    return content;
  } catch (error) {
    console.error("OpenAI API request failed:", error);
    throw error;
  }
}

function createPrompt(
  websiteUrl: string,
  contentType: string,
  tone: string,
  analysis?: any
): string {
  const toneInstructions = {
    professional: "Use a formal, business-like tone with industry terminology",
    casual: "Use a relaxed, conversational tone with everyday language",
    friendly: "Use a warm, approachable tone that builds trust",
    enthusiastic: "Use an energetic, exciting tone that creates urgency",
  };

  const contentTypeInstructions = {
    "social-post":
      "Create a compelling social media post (max 280 characters for Twitter compatibility)",
    "blog-post": "Create a blog post introduction paragraph that hooks readers",
    "product-description":
      "Create a product description that highlights benefits and features",
    newsletter: "Create a newsletter subject line and opening paragraph",
  };

  // Use analysis data if available, otherwise use basic information
  let analysisContext = "";
  if (analysis) {
    analysisContext = `
    Website Analysis:
    - Title: ${analysis.title || "N/A"}
    - Description: ${analysis.description || "N/A"}
    - Category: ${analysis.category || "N/A"}
    - Target Audience: ${analysis.targetAudience?.join(", ") || "N/A"}
    - Content Type: ${analysis.contentType || "N/A"}
    - Sentiment: ${analysis.sentiment || "N/A"}
    - Key Themes: ${analysis.contentAnalysis?.keyThemes?.join(", ") || "N/A"}
    - Keywords: ${analysis.keywords?.join(", ") || "N/A"}
    - Trending Topics: ${analysis.trendingTopics?.join(", ") || "N/A"}
    `;
  }

  return `
    Create marketing content for the website: ${websiteUrl}
    
    ${analysisContext}
    
    Content Type: ${
      contentTypeInstructions[
        contentType as keyof typeof contentTypeInstructions
      ]
    }
    Tone: ${toneInstructions[tone as keyof typeof toneInstructions]}
    
    Requirements:
    - Make it engaging and conversion-focused
    - Include a call-to-action
    - Optimize for the specified platform
    - Keep it authentic and valuable to the audience
    - Use the analysis data to create highly targeted content
    - Incorporate relevant keywords and themes from the analysis
    - Consider the target audience and content type when crafting the message
    
    Generate the content now:
  `;
}

function generateFallbackContent(
  websiteUrl: string,
  contentType: string,
  tone: string,
  analysis?: any
): string {
  throw new Error("AI content generation failed. Please try again.");
}
